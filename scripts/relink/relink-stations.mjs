// The one-off relink of ADR 0010: the station links a road route is owed under the rule it now
// follows (servedBy: a road route stops at a train's or the Carousel's station it passes, never a
// ferry's), written as SQL for the owner to run. Links are written when a direction or a hotspot is
// saved, so every direction saved before the rule changed lacks them.
//
//   node --experimental-strip-types --import ./scripts/node/ts-resolve.mjs scripts/relink/relink-stations.mjs
//                                    dry run: reads, prints what it would add, writes nothing
//   ... scripts/relink/relink-stations.mjs --write
//                                    also writes supabase/apply/20261127120000_relink_stations_*.sql
//
// It reads the database as the publish does (read-database.mjs: the publishable key, the published
// rows only, nothing written) and works each direction's links out with the studio's own save rule
// (hintuanLinksFor) against the direction's full stored line, so each `stop_sequence` is the one a
// save would store. Only the station links the rule adds are written; any other difference between
// the stored links and the rule (a box moved since its last save, say) is printed and left alone:
// that is not this relink's to change.
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { hintuanLinksFor } from '../../src/features/studio/data/route-draft-edits.ts';
import { databaseConfig, databaseReader } from '../publish/read-database.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const NAME = '20261127120000_relink_stations';
const OUT = join(ROOT, 'supabase', 'apply');

/** The relink planned from the rows the publish reads: what to add, and what else differs. */
export function planRelink({ directionRows, hotspotRows, linkRows }) {
  const stopById = new Map(hotspotRows.map((s) => [s.id, s]));
  const add = [];
  const other = [];
  for (const v of directionRows) {
    const line = v.shape?.coordinates;
    if (!Array.isArray(line) || line.length < 2 || !v.route) continue;
    const route = {
      mode: v.route.mode,
      routeCode: v.route.route_code ?? null,
      isLoop: v.route.is_loop === true,
    };
    const { fresh, managed } = hintuanLinksFor(line, hotspotRows, route);
    const stored = new Map(
      linkRows.filter((l) => l.route_variant_id === v.id).map((l) => [l.stop_id, l.stop_sequence]),
    );
    const label = `${v.direction_name ?? v.id}`;
    for (const l of fresh) {
      const stop = stopById.get(l.stop_id);
      if (stored.has(l.stop_id)) {
        if (stored.get(l.stop_id) !== l.stop_sequence)
          other.push(
            `${label}: ${stop?.name} stored at ${stored.get(l.stop_id)}, the rule says ${l.stop_sequence}`,
          );
      } else if (stop?.line) {
        add.push({
          variantId: v.id,
          routeId: v.route.id,
          stopId: l.stop_id,
          sequence: l.stop_sequence,
          label,
          stop: stop.name,
        });
      } else {
        other.push(`${label}: passes ${stop?.name} but is not linked`);
      }
    }
    for (const stopId of stored.keys()) {
      if (managed.has(stopId) && !fresh.some((l) => l.stop_id === stopId))
        other.push(
          `${label}: linked to ${stopById.get(stopId)?.name}, which the rule does not list`,
        );
    }
  }
  return { add, other };
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const valuesOf = (add) =>
  add.map((a) => `    (${q(a.variantId)}::uuid, ${q(a.stopId)}::uuid, ${a.sequence})`).join(',\n');
const header = (what) =>
  `-- ParaPo — ${what}\n-- Generated by scripts/relink/relink-stations.mjs on ${new Date().toISOString().slice(0, 10)}; ADR 0010.\n` +
  `-- Run as postgres in the SQL editor. See supabase/apply/README.md, "The station relink".\n`;

/** The three files: the read-only check, the apply and the revert. */
export function relinkSql(add) {
  const routeIds = [...new Set(add.map((a) => a.routeId))];
  const stopIds = [...new Set(add.map((a) => a.stopId))];
  const planned = `with planned(route_variant_id, stop_id, stop_sequence) as (values\n${valuesOf(add)}\n)`;
  const draftsOpen =
    `select count(*) from public.draft d where (d.kind = 'route' and d.subject_id in (${routeIds.map((id) => `${q(id)}::uuid`).join(', ')}))` +
    ` or (d.kind = 'hotspot' and d.subject_id in (${stopIds.map((id) => `${q(id)}::uuid`).join(', ')}))`;
  const check =
    header('read-only dry run of the station relink. Changes nothing.') +
    `${planned}\nselect * from (values\n` +
    `  ('planned links', (select count(*) from planned)),\n` +
    `  ('already linked (0 before the apply; ${add.length} after)', (select count(*) from planned p join public.route_stop s using (route_variant_id, stop_id))),\n` +
    `  ('direction or station gone (must be 0)', (select count(*) from planned p where not exists (select 1 from public.route_variant v where v.id = p.route_variant_id) or not exists (select 1 from public.stop s where s.id = p.stop_id and s.line is not null))),\n` +
    `  ('open drafts on these routes or stations (must be 0)', (${draftsOpen})),\n` +
    `  ('route_stop rows now', (select count(*) from public.route_stop))\n` +
    `) as t(what, n);\n`;
  const apply =
    header(`the station relink: adds ${add.length} links, removes none. One transaction.`) +
    `-- Refuses, changing nothing, while a draft is open on a route or station it touches (a link\n` +
    `-- write bumps both revisions, which would make that draft stale), or when a planned direction or\n` +
    `-- station is gone. Safe to run twice: a link already there is left as it is.\n` +
    `begin;\ndo $$\ndeclare\n  n integer;\nbegin\n` +
    `  if (${draftsOpen}) > 0 then\n    raise exception 'relink: a draft is open on a route or station it touches. Nothing was changed.';\n  end if;\n` +
    `  ${planned.replace(/\n/g, '\n  ')}\n  insert into public.route_stop (route_variant_id, stop_id, stop_sequence)\n` +
    `  select p.route_variant_id, p.stop_id, p.stop_sequence from planned p\n` +
    `  join public.route_variant v on v.id = p.route_variant_id\n` +
    `  join public.stop s on s.id = p.stop_id and s.line is not null\n` +
    `  on conflict (route_variant_id, stop_id) do nothing;\n` +
    `  get diagnostics n = row_count;\n  raise notice 'relink: % link(s) added', n;\nend;\n$$;\ncommit;\n`;
  const revert =
    header(
      `undo of the station relink: removes exactly the ${add.length} links it adds, whatever their sequence.`,
    ) +
    `begin;\n${planned}\ndelete from public.route_stop s using planned p\n` +
    `where s.route_variant_id = p.route_variant_id and s.stop_id = p.stop_id;\ncommit;\n`;
  return { check, apply, revert };
}

async function main() {
  const config = databaseConfig(ROOT);
  if (!config)
    throw new Error(
      'No database address or publishable key (.env.production, or SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY).',
    );
  const rows = await databaseReader(config).tables();
  const { add, other } = planRelink(rows);
  for (const a of add) console.log(`+ ${a.label}: ${a.stop} @${a.sequence}`);
  console.log(
    `\n${add.length} station link(s) to add, 0 to remove, on ${new Set(add.map((a) => a.variantId)).size} direction(s).`,
  );
  if (other.length) console.log(`\nLeft alone (not this relink's):\n  ${other.join('\n  ')}`);
  if (!process.argv.includes('--write')) return;
  if (add.length === 0) return console.log('Nothing to write.');
  const sql = relinkSql(add);
  for (const [part, text] of Object.entries(sql))
    writeFileSync(join(OUT, `${NAME}_${part}.sql`), text);
  console.log(`\nWrote supabase/apply/${NAME}_{check,apply,revert}.sql`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();

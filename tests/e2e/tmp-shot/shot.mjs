import { open, page } from '../lib/save-studio.mjs';
const dir = process.argv[2];
await page.waitForTimeout(1500);
await page.screenshot({ path: `${dir}/studio-wide.png` });
const phone = await open(true, '/studio/', true);
await phone.waitForTimeout(2500);
await phone.screenshot({ path: `${dir}/studio-phone.png` });
const pub = await open(false, '/', false);
await pub.waitForTimeout(3000);
await pub.screenshot({ path: `${dir}/public-wide.png` });
process.exit(0);
